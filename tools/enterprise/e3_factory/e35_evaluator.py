#!/usr/bin/env python3
"""E3.5 independent CI evaluator. Fixture restoration is NEVER an AI repair."""
from __future__ import annotations
import hashlib
import json
from pathlib import Path
import shutil
import sys

import e33_evaluator as evaluator
import e35_real_model_trial as trial
import worker

BASE = worker.REPO / "target/e3-factory"


def sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def score_case(case_id: str, policy: str) -> dict:
    if case_id not in trial.CASES or policy not in (
            "MODEL_ABSTAIN_OR_INVALID", "POLICY_REJECTED", "POLICY_ACCEPTED"):
        raise ValueError("E35_SCORE_INPUT_NOT_ALLOWED")
    category, _ = trial.CASES[case_id]
    folder = BASE / "e35" / case_id
    source_file = BASE / "site" / trial.gate.CATEGORIES[category][0]
    original = (trial.gate.worker.HERE / source_file.name).read_bytes()
    seed = json.loads((BASE / "e33" / case_id / "seed.json").read_text("utf-8"))
    pre = json.loads((BASE / "e33" / case_id / "browser-before.json").read_text("utf-8"))
    info = json.loads((folder / "inference.json").read_text("utf-8"))
    if (info.get("modelCalls") != 1 or info.get("realGeneratedTokens", 0) < 1
            or info.get("ownerApproved") is not False
            or info.get("textWasExecuted") is not False
            or info.get("category") != category
            or pre.get("passed") is not False
            or pre.get("failureCode") != trial.CASES[case_id][1]):
        raise ValueError("E35_INFERENCE_OR_REAL_FAILURE_PROOF_INVALID")
    if source_file.is_symlink() or not source_file.is_file():
        raise ValueError("E35_SCORER_SOURCE_NOT_REGULAR")
    now = source_file.read_bytes()
    browser_after_path = BASE / "e32" / category / "diagnosis.json"
    after = (json.loads(browser_after_path.read_text("utf-8"))
             if policy == "POLICY_ACCEPTED" else None)
    verified = bool(policy == "POLICY_ACCEPTED"
                    and after.get("evidenceClass") == "E32_REAL_CHROMIUM_FAULT_CONTRACT"
                    and after.get("passed") is True
                    and after.get("failureCode") is None
                    and now == original
                    and sha(now) == seed["expectedCleanSha256"])
    if policy != "POLICY_ACCEPTED" and sha(now) != seed["beforeSha256"]:
        raise ValueError("E35_REJECTED_MODEL_ADVICE_MUTATED_SOURCE")
    # Policy accepted but Chromium failed is a reported *failed* model repair.
    # Only the frozen fixture runner may reset the source for the next test.
    if not verified and now not in (original, evaluator.CASES[case_id][3].encode()):
        # The final tuple element is a replacement span, not a full source:
        # do not use it as an oracle. Compare against independently generated
        # seeded hash instead.
        if sha(now) != seed["beforeSha256"]:
            raise ValueError("E35_FAILED_PATCH_SOURCE_DRIFT")
    if policy == "POLICY_ACCEPTED":
        shutil.copy2(browser_after_path, folder / "browser-after.json")
        shot = BASE / "e32" / category / "after-browser.png"
        if shot.is_file():
            shutil.copy2(shot, folder / "after-browser.png")
    current = BASE / "e33" / "current"
    for filename in ("advisory.json", "proposal.json", "receipt.json"):
        src = current / filename
        if src.is_symlink():
            raise ValueError("E35_SYMLINK_EVIDENCE_REJECTED")
        if src.is_file():
            shutil.copy2(src, folder / filename)
    result = {
        "evidenceClass": "E35_INDEPENDENT_POLICY_AND_BROWSER_CASE_SCORE",
        "caseId": case_id, "category": category,
        "realModelCalled": True, "tokensGenerated": info["realGeneratedTokens"],
        "responseClass": info["responseClass"], "policyOutcome": policy,
        "modelBrowserVerifiedRepair": verified,
        "sourceSha256AfterTrial": sha(now),
        "fixtureResetPerformedByCIForNextCase": not verified,
        "modelOutputExecutedDirectly": False, "ownerApprovalGranted": False,
        "userPcUsed": False, "productionPublished": False,
    }
    (folder / "score.json").write_text(
        json.dumps(result, sort_keys=True, indent=2) + "\n", encoding="utf-8")
    if not verified:
        # Cleanup is NOT a model repair. Only reset to the separately checked
        # canonical generated bytes when the bad fixture is still recognized.
        if sha(now) != seed["beforeSha256"]:
            raise ValueError("E35_UNRECOGNIZED_OUTPUT_REFUSED_FIXTURE_RESET")
        source_file.write_bytes(original)
    if source_file.read_bytes() != original:
        raise ValueError("E35_FINAL_SITE_NOT_CANONICAL")
    print("E35_CASE_SCORED",case_id,"model_browser_verified",str(verified),
          "policy",policy)
    return result


def summary() -> dict:
    records=[]
    for case_id in trial.CASES:
        item=json.loads((BASE / "e35" / case_id / "score.json").read_text("utf-8"))
        if item.get("caseId") != case_id or item.get("realModelCalled") is not True:
            raise ValueError("E35_MISSING_REAL_INFERENCE_CASE")
        records.append(item)
    passed=sum(int(x["modelBrowserVerifiedRepair"]) for x in records)
    report={
        "evidenceClass":"E35_REAL_QWEN_CODER_1_5B_THREE_CASE_CPU_EVALUATION",
        "attempts":len(records), "realModelResponses":len(records),
        "independentBrowserVerifiedModelRepairs":passed,
        "failedOrRejectedModelRepairs":len(records)-passed,
        "modelName":trial.MODEL,
        "policyAccepted":sum(x["policyOutcome"]=="POLICY_ACCEPTED" for x in records),
        "explicitAbstainOrInvalid":sum(
            x["policyOutcome"]=="MODEL_ABSTAIN_OR_INVALID" for x in records),
        "cases":records, "mockModelCallsCounted":0,
        "trulyBlindRealWorldDefectsTested":False,
        "userPcUsed":False, "productionPublished":False,
        "ownerAuthenticated":False, "ownerApprovalGranted":False,
        "stage45Certification":False,
    }
    (BASE / "e35" / "evaluation-summary.json").write_text(
        json.dumps(report,indent=2,sort_keys=True)+"\n", encoding="utf-8")
    print("E35_ACTUAL_REAL_MODEL_MULTI_CASE_SCORE",json.dumps({
        k:report[k] for k in ("attempts","realModelResponses",
        "independentBrowserVerifiedModelRepairs","failedOrRejectedModelRepairs")}))
    return report


if __name__=="__main__":
    if len(sys.argv)==4 and sys.argv[1]=="score":
        score_case(sys.argv[2],sys.argv[3])
    elif sys.argv[1:]==["summary"]:
        summary()
    else:
        raise ValueError("E35_SCORE_ONLY_EXPLICIT_CASE_OR_SUMMARY")
