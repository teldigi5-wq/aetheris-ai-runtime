-- Aetheris E2.2B-2, schema contract v1; apply ONLY through a reviewed DB migration.
-- Not a positive approval mechanism. NO approved/consumed/token state exists here.
-- Run with an administrator or dedicated migration role, not an AI worker.
BEGIN;
CREATE TABLE enterprise_design_review_intents (
    id varchar(36) PRIMARY KEY,
    project_id varchar(80) NOT NULL,
    company_id varchar(80) NOT NULL,
    division_id varchar(80) NOT NULL,
    brief_digest varchar(64) NOT NULL,
    storyboard_digest varchar(64) NOT NULL,
    manifest_digest varchar(64) NOT NULL,
    issued_at timestamp(6) with time zone NOT NULL,
    expires_at timestamp(6) with time zone NOT NULL,
    status varchar(64) NOT NULL,
    CONSTRAINT e22b_intent_uuid CHECK (
        id ~ '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$'
    ),
    CONSTRAINT e22b_intent_project CHECK (
        project_id ~ '^[a-z0-9]+(-[a-z0-9]+)*$'
        AND company_id ~ '^[a-z0-9]+(-[a-z0-9]+)*$'
        AND division_id ~ '^[a-z0-9]+(-[a-z0-9]+)*$'
    ),
    CONSTRAINT e22b_intent_digest CHECK (
        brief_digest ~ '^[0-9a-f]{64}$'
        AND storyboard_digest ~ '^[0-9a-f]{64}$'
        AND manifest_digest ~ '^[0-9a-f]{64}$'
    ),
    CONSTRAINT e22b_intent_ttl CHECK (
        expires_at = issued_at + interval '15 minutes'
    ),
    CONSTRAINT e22b_intent_no_approval CHECK (
        status = 'PENDING_OWNER_AUTHENTICATION_UNAVAILABLE'
    )
);

CREATE TABLE enterprise_design_review_denials (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    intent_id varchar(36) NOT NULL,
    reason varchar(64) NOT NULL,
    occurred_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT e22b_denial_intent_fk FOREIGN KEY (intent_id)
        REFERENCES enterprise_design_review_intents(id) ON DELETE RESTRICT,
    CONSTRAINT e22b_denial_reason CHECK (reason IN (
        'E22B_STATUS_NOT_AUTHORIZABLE',
        'E22B_INTENT_EXPIRED',
        'E22B_ARTIFACT_ABSENT',
        'E22B_OWNER_AUTHENTICATION_NOT_CONNECTED',
        'E22B_SCOPE_OR_CONTENT_CHANGED',
        'E22B_UNVERIFIED_ARTIFACT'
    ))
);

CREATE INDEX e22b_denials_intent_order
    ON enterprise_design_review_denials (intent_id, id);

-- The migration owner retains DDL privileges; runtime credentials must
-- be SEPARATE and granted only SELECT/INSERT on these objects.
REVOKE ALL ON enterprise_design_review_intents FROM PUBLIC;
REVOKE ALL ON enterprise_design_review_denials FROM PUBLIC;
REVOKE ALL ON SEQUENCE enterprise_design_review_denials_id_seq FROM PUBLIC;
COMMIT;
